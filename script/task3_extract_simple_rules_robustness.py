"""
Task 3: extract simple pricing-adjustment rules and test robustness.

This script compresses the task-2 equal-weight optimal alpha path into shallow
decision-tree rules. The learned rules are then used as an operational policy:

    u_i,t = alpha_rule_i,t * f_i,t

where f_i,t is the first-question theoretical adjustment. Robustness is checked
under several international-oil-volatility scenarios generated by scaling and
shifting the theoretical adjustment path.

Outputs:
    result/task3_rule_tree_gasoline.txt
    result/task3_rule_tree_diesel.txt
    result/task3_rule_fit_metrics.csv
    result/task3_simple_rule_alpha_path.csv
    result/task3_simple_rule_strategy_comparison.csv
    result/task3_simple_rule_dimension_mean_summary.csv
    result/task3_robustness_scenario_summary.csv
    result/task3_robustness_dimension_means.csv
    result/task3_simple_rule_dimension_means.png
    result/task3_robustness_total_loss.png
"""

